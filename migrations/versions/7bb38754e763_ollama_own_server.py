def give_users_the_operator_url(conn) -> None:
    """Ollama no longer has an operator default: each user who had it enabled keeps the server
    they were silently using, as their own credential. Then the admin setting is dropped."""
    url = conn.execute(sa.text(
        "SELECT value #>> '{}' FROM server_settings WHERE key = 'ollama_url'")).scalar()
    url = url or os.environ.get("TA_OLLAMA_URL") or DEFAULT_URL
    users = [r[0] for r in conn.execute(sa.text(
        "SELECT user_id FROM user_settings WHERE key = 'mt_enabled' "
        "AND value_json @> CAST('[\"ollama\"]' AS jsonb)"))]
    for user_id in users:
        done = conn.execute(sa.text(
            "UPDATE api_credentials SET endpoint_url = :url WHERE user_id = :u "
            "AND kind = 'ollama' AND name = '' AND endpoint_url = ''"),
            {"url": url, "u": user_id}).rowcount
        if not done:  # an existing credential with its own URL is left alone
            conn.execute(sa.text(
                "INSERT INTO api_credentials (user_id, kind, name, secret_enc, endpoint_url) "
                "VALUES (:u, 'ollama', '', :secret, :url) "
                "ON CONFLICT (user_id, kind, name) DO NOTHING"),
                {"u": user_id, "secret": encrypt_secret(""), "url": url})
    conn.execute(sa.text("DELETE FROM server_settings WHERE key = 'ollama_url'"))


